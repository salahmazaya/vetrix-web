type GlobalSlug = "header" | "cta" | "footer" | "home" | "faq" | "contact" | "aiCore" | "about" | "solutions";

const filled: Record<GlobalSlug, (doc: Record<string, unknown>) => unknown> = {
  header: (doc) => (doc.links as { label?: string }[] | undefined)?.[0]?.label,
  cta: (doc) => doc.title,
  footer: (doc) => doc.tagline,
  home: (doc) => (doc.hero as { title?: string } | undefined)?.title,
  faq: (doc) => doc.title,
  contact: (doc) => (doc.form as { title?: string } | undefined)?.title,
  aiCore: (doc) => (doc.brain as { title?: string } | undefined)?.title,
  about: (doc) => (doc.identity as { title?: string } | undefined)?.title,
  solutions: (doc) => (doc.deliver as { title?: string } | undefined)?.title,
};

function homeArabic() {
  const process = content.home.process;
  return {
    ...arabic.home,
    process: {
      ...arabic.home.process,
      sources: process.sources.map((tile) => ({ name: tile.name })),
      groups: arabic.home.process.groups.map((group, index) => ({
        label: group.label,
        tiles: process.groups[index].tiles.map((tile) => ({ name: tile.name })),
      })),
    },
  };
}

const translated: Record<GlobalSlug, unknown> = {
  header: arabic.header,
  cta: arabic.cta,
  footer: arabic.footer,
  home: homeArabic(),
  faq: arabic.faq,
  contact: arabic.contact,
  aiCore: arabic.aiCore,
  about: arabic.about,
  solutions: arabic.solutions,
};

/** Fills Arabic the first time it is empty, without touching English or shared images and links. */
export async function seedArabic(payload: Payload) {
  const slugs = Object.keys(filled) as GlobalSlug[];
  for (const slug of slugs) {
    const doc = (await payload.findGlobal({
      slug,
      locale: "ar",
      fallbackLocale: false,
      depth: 0,
    })) as unknown as Record<string, unknown>;
    if (filled[slug](doc)) continue;
    payload.logger.info(`Seeding ${slug} in Arabic...`);
    await payload.updateGlobal({
      slug,
      locale: "ar",
      fallbackLocale: false,
      context: seedContext,
      data: overlay(withoutMeta(doc), translated[slug]) as never,
    });
  }
}
