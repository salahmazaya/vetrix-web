const meta = new Set(["id", "createdAt", "updatedAt", "globalType", "_status"]);

/** Copies Arabic strings onto the existing rows, leaving images, links, and ids in place. */
function overlay(current: unknown, translated: unknown): unknown {
  if (Array.isArray(translated)) {
    const rows = Array.isArray(current) ? current : [];
    return translated.map((item, index) => overlay(rows[index], item));
  }
  if (translated && typeof translated === "object") {
    const base =
      current && typeof current === "object" && !Array.isArray(current)
        ? { ...(current as Record<string, unknown>) }
        : {};
    for (const [key, value] of Object.entries(translated as Record<string, unknown>)) {
      base[key] = overlay(base[key], value);
    }
    return base;
  }
  return translated;
}

function withoutMeta(doc: Record<string, unknown>) {
  return Object.fromEntries(Object.entries(doc).filter(([key]) => !meta.has(key)));
}

